"""Build corpus-manifest.csv and corpus-manifest.md for the 55 papers.

Sources: selection/selection.json (bibliographic records), selection/corpus-55.md (inclusion reason per paper),
and the files under development-50/ and heldout-5/ (SHA256, page count, presence of text and card).
Usage: python tools/build_manifest.py
"""
import csv, hashlib, json, re
from pathlib import Path
import pypdf

ROOT = Path(__file__).resolve().parents[1]
SPLIT_DIR = {'extraction': 'development-50', 'validation': 'heldout-5'}
SPLIT_NAME = {'extraction': 'development', 'validation': 'held-out'}


def main():
    sel = json.load(open(ROOT / 'selection' / 'selection.json', encoding='utf-8'))
    reasons = {}
    for line in (ROOT / 'selection' / 'corpus-55.md').read_text(encoding='utf-8').splitlines():
        m = re.match(r'\| ([EV]\d\d) \|.*\| ([^|]+) \|\s*$', line)
        if m:
            reasons[m.group(1)] = m.group(2).strip()
    rows = []
    for r in sel:
        d = SPLIT_DIR[r['split']]
        pdf = ROOT / d / 'papers' / f"{r['id']}.pdf"
        text = ROOT / d / 'text' / f"{r['id']}.txt"
        card = ROOT / d / 'cards' / f"{r['id']}-card.md"
        rows.append({
            'id': r['id'], 'split': SPLIT_NAME[r['split']], 'year': r['year'], 'authors': r['authors'],
            'title': r['title'], 'journal': r['journal'], 'doi': r['doi'],
            'inclusion_reason_zh': reasons.get(r['id'], ''),
            'pdf': pdf.relative_to(ROOT).as_posix(), 'pages': len(pypdf.PdfReader(pdf).pages),
            'pdf_sha256': hashlib.sha256(pdf.read_bytes()).hexdigest(),
            'text': text.relative_to(ROOT).as_posix() if text.exists() else '',
            'card': card.relative_to(ROOT).as_posix() if card.exists() else '',
        })
    assert len(rows) == 55 and all(x['text'] and x['card'] and x['inclusion_reason_zh'] for x in rows)
    with open(ROOT / 'corpus-manifest.csv', 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    md = ['# Corpus manifest (55 papers)', '',
          'Generated by `tools/build_manifest.py`. Full fields, including authors and SHA256, are in `corpus-manifest.csv`.', '',
          '| ID | Split | Year | Title | Journal | DOI | Pages | Files | Inclusion reason |',
          '|---|---|---:|---|---|---|---:|---|---|']
    for x in rows:
        md.append(f"| {x['id']} | {x['split']} | {x['year']} | {x['title']} | {x['journal']} | "
                  f"[{x['doi']}](https://doi.org/{x['doi']}) | {x['pages']} | "
                  f"[PDF]({x['pdf']}) · [text]({x['text']}) · [card]({x['card']}) | {x['inclusion_reason_zh']} |")
    (ROOT / 'corpus-manifest.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    print('rows', len(rows))


if __name__ == '__main__':
    main()
